//! Init command: interactive prompting and config/workflow rendering.
//!
//! Owns the `init` subcommand end to end: `InitArgs` (clap surface), the
//! interactive option prompts, the generated `pretender.toml` and GitHub
//! Actions workflow contents, and the preset threshold tables both are
//! built from.
//!
//! # Responsibilities
//! Prompt for mode/preset/languages/flags (overridable via CLI flags),
//! render the config document, scaffold it through `genesis`, and print
//! the gate+strict migration hint. Hook installation and the workflow
//! write stay at the crate root and are invoked from here.
//!
//! # Rationale
//! Extracted from main.rs (pretender-5zo.2.3) so the bin crate root keeps
//! shrinking; the oversized functions were split into verbatim-behaving
//! helpers while moving so prompts, generated bytes, and side-effect
//! ordering stay identical within the structural limits.
use crate::cli::args::ModeArg;
use crate::cli::hooks::{install_hook, write_github_ci_workflow};
use crate::cli::Executable;
use anyhow::{anyhow, Context, Result};
use clap::{Parser, ValueEnum};
use genesis::git_hooks::HookName;
use genesis::scaffold;
use render::render_init_config;
use std::io::{self, Read, Write};
use std::path::Path;
use std::process::ExitCode;

mod render;

pub(crate) use render::github_ci_workflow_contents;

#[cfg(test)]
mod tests;

/// `pretender init`: scaffold a pretender.toml and optional extras.
#[derive(Parser, Debug)]
pub(crate) struct InitArgs {
    /// Skip prompts, use best-guess defaults
    #[arg(long)]
    non_interactive: bool,
    /// Override default mode
    #[arg(long, value_enum)]
    mode: Option<ModeArg>,
    /// Threshold preset to write into the generated config
    #[arg(long, value_enum)]
    preset: Option<ThresholdPreset>,
}

/// Threshold strictness preset for `init` (update-app-threshold-defaults):
/// selects which threshold tables the generated pretender.toml emits.
#[derive(Clone, Copy, Debug, PartialEq, Eq, ValueEnum)]
pub(crate) enum ThresholdPreset {
    Default,
    Strict,
}

struct InitOptions {
    mode: ModeArg,
    preset: ThresholdPreset,
    languages: Vec<String>,
    install_hook: bool,
    generate_github_actions: bool,
}

impl Executable for InitArgs {
    fn run(&self) -> Result<ExitCode> {
        let options = resolve_init_options(self)?;
        let cwd = std::env::current_dir().context("failed to get current directory")?;
        write_init_scaffold(&cwd, &options)?;
        print_gate_strict_hint(&options);
        register_in_genesis_manifest(&cwd)?;
        install_init_extras(&options)?;
        Ok(ExitCode::SUCCESS)
    }
}

/// Register the installed tool in the genesis discovery manifest.
fn register_in_genesis_manifest(cwd: &Path) -> Result<()> {
    genesis::discovery::register(
        cwd,
        "pretender",
        "Multi-language structural code-quality checks",
        "file",
        "pretender.toml",
    )
    .map_err(|e| anyhow::anyhow!("failed to register in genesis manifest: {e}"))
}

/// Optional extras chosen at prompt time: pre-commit hook and workflow.
fn install_init_extras(options: &InitOptions) -> Result<()> {
    if options.install_hook {
        install_hook(HookName::PreCommit)?;
    }
    if options.generate_github_actions {
        write_github_ci_workflow()?;
    }
    Ok(())
}

/// Prompt-driven options, or the non-interactive best-guess defaults.
fn resolve_init_options(args: &InitArgs) -> Result<InitOptions> {
    if args.non_interactive {
        return Ok(InitOptions {
            mode: args.mode.unwrap_or(ModeArg::Tiered),
            preset: args.preset.unwrap_or(ThresholdPreset::Default),
            languages: vec!["auto".to_string()],
            install_hook: false,
            generate_github_actions: false,
        });
    }
    prompt_init_options(args.mode, args.preset)
}

/// Render the config and scaffold it into `cwd` via genesis.
fn write_init_scaffold(cwd: &Path, options: &InitOptions) -> Result<()> {
    // Use genesis::scaffold to write the config and set up directories
    let config_content = render_init_config(options);
    let result = scaffold::Scaffold::new(cwd)
        .default_config("pretender.toml", config_content)
        .build()
        .context("failed to scaffold init")?;

    if result.created.is_empty() && result.existed.iter().any(|p| p.ends_with("pretender.toml")) {
        eprintln!("pretender.toml already exists, skipping");
    }
    Ok(())
}

/// Strict on gate is an immediate wall of violations on an existing
/// codebase — point at the migration path (spec: Strict Preset Gate
/// Hint). Printed whenever gate+strict combine, written or not.
fn print_gate_strict_hint(options: &InitOptions) {
    if options.mode == ModeArg::Gate && options.preset == ThresholdPreset::Strict {
        println!(
            "Strict preset with gate mode: existing code will likely violate the tighter thresholds."
        );
        println!(
            "Baseline the current state first: pretender check --adopt, or use mode = \"tiered\" with an advisory lease."
        );
    }
}

fn prompt_init_options(
    mode_override: Option<ModeArg>,
    preset_override: Option<ThresholdPreset>,
) -> Result<InitOptions> {
    let mut stdin = io::stdin().lock();
    let mut stdout = io::stdout().lock();
    let mode = prompt_mode(&mut stdin, &mut stdout, mode_override)?;
    // An explicit --preset suppresses the prompt (mirrors --mode).
    let preset = prompt_preset(&mut stdin, &mut stdout, preset_override)?;
    let (languages, install_hook, generate_github_actions) =
        prompt_languages_and_flags(&mut stdin, &mut stdout)?;

    Ok(InitOptions {
        mode,
        preset,
        languages,
        install_hook,
        generate_github_actions,
    })
}

/// An explicit `--mode` suppresses the prompt.
fn prompt_mode(
    stdin: &mut dyn Read,
    stdout: &mut dyn Write,
    mode_override: Option<ModeArg>,
) -> Result<ModeArg> {
    if let Some(mode) = mode_override {
        return Ok(mode);
    }
    let answer = prompt(stdin, stdout, "Mode (guidance/tiered/gate) [tiered]: ")?;
    match answer.trim().to_ascii_lowercase().as_str() {
        "" | "tiered" => Ok(ModeArg::Tiered),
        "guidance" => Ok(ModeArg::Guidance),
        "gate" => Ok(ModeArg::Gate),
        other => Err(anyhow!("invalid mode: {other}")),
    }
}

/// An explicit `--preset` suppresses the prompt.
fn prompt_preset(
    stdin: &mut dyn Read,
    stdout: &mut dyn Write,
    preset_override: Option<ThresholdPreset>,
) -> Result<ThresholdPreset> {
    if let Some(preset) = preset_override {
        return Ok(preset);
    }
    let answer = prompt(
        stdin,
        stdout,
        "Threshold preset (default/strict) [default]: ",
    )?;
    match answer.trim().to_ascii_lowercase().as_str() {
        "" | "default" => Ok(ThresholdPreset::Default),
        "strict" => Ok(ThresholdPreset::Strict),
        other => Err(anyhow!("invalid preset: {other}")),
    }
}

/// Prompt for the languages list and the two yes/no follow-ups.
fn prompt_languages_and_flags(
    stdin: &mut dyn Read,
    stdout: &mut dyn Write,
) -> Result<(Vec<String>, bool, bool)> {
    let languages = parse_languages(&prompt(
        stdin,
        stdout,
        "Languages (auto or comma-separated list) [auto]: ",
    )?);
    let install_hook = parse_yes_no(&prompt(stdin, stdout, "Install pre-commit hook? [y/N]: ")?);
    let generate_github_actions = parse_yes_no(&prompt(
        stdin,
        stdout,
        "Generate GitHub Actions workflow? [y/N]: ",
    )?);
    Ok((languages, install_hook, generate_github_actions))
}

fn prompt(stdin: &mut dyn Read, stdout: &mut dyn Write, message: &str) -> Result<String> {
    write!(stdout, "{message}")?;
    stdout.flush()?;

    let mut buf = Vec::new();
    let mut byte = [0u8; 1];
    loop {
        match stdin.read(&mut byte)? {
            0 => break,
            _ if byte[0] == b'\n' => break,
            _ => buf.push(byte[0]),
        }
    }

    Ok(String::from_utf8_lossy(&buf).trim().to_string())
}

fn parse_languages(input: &str) -> Vec<String> {
    let trimmed = input.trim();
    if trimmed.is_empty() || trimmed.eq_ignore_ascii_case("auto") {
        return vec!["auto".to_string()];
    }

    let mut languages: Vec<String> = trimmed
        .split(',')
        .map(|value| value.trim().to_ascii_lowercase())
        .filter(|value| !value.is_empty())
        .collect();
    if languages.is_empty() {
        languages.push("auto".to_string());
    }
    languages
}

fn parse_yes_no(input: &str) -> bool {
    matches!(input.trim().to_ascii_lowercase().as_str(), "y" | "yes")
}
